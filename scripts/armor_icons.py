def pixels(name):
    palette, rows = ART[name]
    colors = [tuple(bytes.fromhex(color)) for color in palette]
    alphabet = '.0123456789ABCDEF'
    assert len(rows) == 16 and all(len(row) == 16 for row in rows)
    return [colors[alphabet.index(code)] for row in rows for code in row]

def content(png, assets):
    for name in ART:
        png(assets / ('textures/item/' + name + '.png'), pixels(name))
